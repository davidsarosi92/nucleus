// Memory for an AI application (PLAN.md section M14.24): a knowledge base
// the assistant cites — and a citation read back as it was —, a memory of
// its own for each user, a record of what each reply read, and a user
// erased on request.
//
//   node examples/js/memory.ts                    # the local server
//   node examples/js/memory.ts file:assistant.db  # in this process
//   node examples/js/memory.ts nucleus://nucleus:nucleus@127.0.0.1:20035/nucleus
//
// The model here is `hashing` — lexical vectors, no network — so it runs
// anywhere; a real application names a model of meaning instead
// (`CREATE MODEL bge USING local WITH (huggingface = 'BAAI/bge-small-en-v1.5')`,
// or `USING openai WITH (…)`).  A citation of an older version is read
// back while the history keeps it: start the server with `--history 1h`.

import { connect, NucleusError, type Client } from "../../drivers/js/src/index.ts";

const port = process.env.NUCLEUS_PORT ?? "20035";
const url = process.argv[2] ?? `nucleus://nucleus:nucleus@127.0.0.1:${port}/nucleus`;
const tables = ["kb_chunks", "kb_docs", "assistant_memory", "tickets"];

function check(ok: boolean, what: unknown): void {
  if (!ok) throw new Error(`unexpected: ${JSON.stringify(what)}`);
}

async function setup(db: Client): Promise<void> {
  for (const t of tables) await db.query(`DROP TABLE IF EXISTS ${t}`);
  await db.query("DROP MODEL IF EXISTS words");
  await db.query("CREATE MODEL words USING hashing WITH (dimensions = 256)");
  // The knowledge base: documents, kept cut into chunks (in the writer's
  // transaction), each chunk with a vector made in the background and a
  // text index — searched by both at once.
  await db.query("CREATE TABLE kb_docs (id INT PRIMARY KEY, title TEXT, body TEXT)");
  await db.query("CREATE TABLE kb_chunks CHUNKS OF kb_docs (body) BY markdown SIZE 40");
  await db.query("ALTER TABLE kb_chunks ADD COLUMN v vector GENERATED BY EMBEDDING (chunk) USING words");
  await db.query("CREATE INDEX kb_chunks_text ON kb_chunks USING text (chunk)");
  // A memory per user: whose a memory is is its subject.
  await db.query("CREATE MEMORY STORE assistant_memory USING words");
  // Any other table can say whose a row is, so an erasure reaches it.
  await db.query("CREATE TABLE tickets (id INT PRIMARY KEY, customer TEXT, issue TEXT)");
  await db.query("ALTER TABLE tickets SET SUBJECT (customer)");
  // Queries wait for vectors still being made (a demo writes, then reads).
  await db.query("SET embedding.pending = wait");
}

// The chunks that answer `question` best — words and vectors fused — each
// with what cites it: the document, the chunk, the commit read.
async function search(db: Client, question: string, k = 2) {
  const r = await db.query(
    `SELECT id, position, chunk, snapshot_commit() AS as_of FROM kb_chunks
     ORDER BY rrf(score(chunk @@ $1), v <=> embed($1)) DESC LIMIT $2`,
    [question, k],
  );
  return r.records();
}

const db = await connect(url);
console.log("connected:", db.serverVersion);
await setup(db);

await db.executeMany("INSERT INTO kb_docs VALUES ($1, $2, $3)", [
  [1, "Refunds", "# Refunds\n\nA purchase can be returned for a full refund within 30 days. Keep the receipt."],
  [2, "Shipping", "# Shipping\n\nOrders leave the warehouse in two working days. Tracking numbers come by e-mail."],
  [3, "Warranty", "# Warranty\n\nDevices carry a two-year warranty against defects."],
]);

// 1. An answer with its citations.
const [cited] = await search(db, "how many days do I have to return a purchase");
console.log(`answer from doc ${cited.id} chunk ${cited.position} (as of commit ${cited.as_of}):`);
console.log("  ", cited.chunk);
check(String(cited.chunk).includes("30 days"), cited);

// The policy changes; the next answer reads the new text …
await db.query("UPDATE kb_docs SET body = replace(body, '30 days', '14 days') WHERE id = 1");
const [now] = await search(db, "how many days do I have to return a purchase");
check(String(now.chunk).includes("14 days"), now);
// … and the old citation still reads what was cited, by its commit.
try {
  const then = await db.query(
    `SELECT chunk FROM kb_chunks AS OF COMMIT ${Number(cited.as_of)} WHERE id = $1 AND position = $2`,
    [cited.id, cited.position],
  );
  console.log("the citation, read back:", then.rows[0][0]);
  check(then.rows[0][0] === cited.chunk, then.rows);
} catch (e) {
  if (!(e instanceof NucleusError) || e.code !== "72000") throw e;
  console.log("(the history no longer holds that commit: start the server with --history 1h)");
}

// 2. A memory per user: each sees only their own.
await db.remember("assistant_memory", "ann", "Ann prefers short answers", { kind: "preference" });
const old = await db.remember("assistant_memory", "ann", "Ann lives in Szeged");
await db.remember("assistant_memory", "ann", "Ann moved to Pécs", { replaces: old.id }); // the old fact kept as history
await db.remember("assistant_memory", "bob", "Bob wants every detail", { kind: "preference" });
await db.query("INSERT INTO tickets VALUES (1, 'ann', 'parcel lost'), (2, 'bob', 'late refund')");
const memories = await db.recall("assistant_memory", "ann", "how should I answer, and where does she live");
const contents = memories.map((m) => m.content).sort();
console.log("ann's memories:", contents);
check(contents.join("|") === "Ann moved to Pécs|Ann prefers short answers", contents);

// 3. What a reply read, recorded under its request id.
const request = `reply-${process.pid}`;
await db.query(`SET request_id = '${request}'`);
await db.recall("assistant_memory", "ann", "how should I answer");
await search(db, "refund");
await db.query("RESET request_id");
const reads = await db.query(
  "SELECT as_of, tables, array_length(ids, 1) AS n FROM nc_catalog.reads WHERE request_id = $1 ORDER BY at",
  [request],
);
for (const r of reads.records()) console.log(request, "read:", r);

// 4. Ann asks to be forgotten: her memories and tickets go, every file is
// scrubbed of them and searched (found === 0 is the proof), the records of
// what was read for her are blanked.  (A backup taken before — BACKUP TO —
// sealed her rows under her key, which this destroys: restored, it leaves
// her out.)
const erased = await db.forgetSubject("ann");
console.log("erased:", erased);
check(erased.rows === 4 && (erased.found === 0 || erased.found === null), erased);
const left = await db.recall("assistant_memory", "ann", "answer");
check(left.length === 0, left);
const bob = await db.recall("assistant_memory", "bob", "answer");
check(bob.length === 1 && bob[0].content === "Bob wants every detail", bob);
const tickets = (await db.query("SELECT customer FROM tickets")).rows.map((r) => r[0]);
check(tickets.join() === "bob", tickets);

for (const t of tables) await db.query(`DROP TABLE ${t}`);
await db.query("DROP MODEL words");
await db.close();
console.log("done");
