"""Memory for an AI application (PLAN.md section M14.24): a knowledge base
the assistant cites — and a citation read back as it was —, a memory of
its own for each user, a record of what each reply read, and a user
erased on request.

    python3 examples/python/memory.py                    # the local server
    python3 examples/python/memory.py file:assistant.db  # in this process
    python3 examples/python/memory.py nucleus://nucleus:nucleus@127.0.0.1:20035/nucleus

The model here is `hashing` — lexical vectors, no network — so it runs
anywhere; a real application names a model of meaning instead
(`CREATE MODEL bge USING local WITH (huggingface = 'BAAI/bge-small-en-v1.5')`,
or `USING openai WITH (…)`).  A citation of an older version is read
back while the history keeps it: start the server with `--history 1h`.
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "drivers", "python"))
import nucleus  # noqa: E402

port = int(os.environ.get("NUCLEUS_PORT", nucleus.DEFAULT_PORT))
url = sys.argv[1] if len(sys.argv) > 1 else f"nucleus://nucleus:nucleus@127.0.0.1:{port}/nucleus"


def setup(db):
    for t in ("kb_chunks", "kb_docs", "assistant_memory", "tickets"):
        db.execute(f"DROP TABLE IF EXISTS {t}")
    db.execute("DROP MODEL IF EXISTS words")
    db.execute("CREATE MODEL words USING hashing WITH (dimensions = 256)")
    # The knowledge base: documents, kept cut into chunks (in the writer's
    # transaction), each chunk with a vector made in the background and a
    # text index — searched by both at once.
    db.execute("CREATE TABLE kb_docs (id INT PRIMARY KEY, title TEXT, body TEXT)")
    db.execute("CREATE TABLE kb_chunks CHUNKS OF kb_docs (body) BY markdown SIZE 40")
    db.execute("ALTER TABLE kb_chunks ADD COLUMN v vector GENERATED BY EMBEDDING (chunk) USING words")
    db.execute("CREATE INDEX kb_chunks_text ON kb_chunks USING text (chunk)")
    # A memory per user: whose a memory is is its subject.
    db.execute("CREATE MEMORY STORE assistant_memory USING words")
    # Any other table can say whose a row is, so an erasure reaches it.
    db.execute("CREATE TABLE tickets (id INT PRIMARY KEY, customer TEXT, issue TEXT)")
    db.execute("ALTER TABLE tickets SET SUBJECT (customer)")
    # Queries wait for vectors still being made (a demo writes, then reads).
    db.execute("SET embedding.pending = wait")


def search(db, question, k=2):
    """The chunks that answer `question` best — words and vectors fused —
    each with what cites it: the document, the chunk, the commit read."""
    return db.execute(
        """SELECT id, position, chunk, snapshot_commit() AS as_of FROM kb_chunks
           ORDER BY rrf(score(chunk @@ $1), v <=> embed($1)) DESC LIMIT $2""",
        [question, k],
    ).records()


with nucleus.connect(url) as db:
    print("connected:", db.server_version)
    setup(db)

    db.execute_many("INSERT INTO kb_docs VALUES ($1, $2, $3)", [
        (1, "Refunds", "# Refunds\n\nA purchase can be returned for a full refund within 30 days. "
                       "Keep the receipt."),
        (2, "Shipping", "# Shipping\n\nOrders leave the warehouse in two working days. "
                        "Tracking numbers come by e-mail."),
        (3, "Warranty", "# Warranty\n\nDevices carry a two-year warranty against defects."),
    ])

    # 1. An answer with its citations.
    found = search(db, "how many days do I have to return a purchase")
    cited = found[0]
    print(f"answer from doc {cited['id']} chunk {cited['position']} (as of commit {cited['as_of']}):")
    print("  ", cited["chunk"])
    assert "30 days" in cited["chunk"]

    # The policy changes; the next answer reads the new text …
    db.execute("UPDATE kb_docs SET body = replace(body, '30 days', '14 days') WHERE id = 1")
    assert "14 days" in search(db, "how many days do I have to return a purchase")[0]["chunk"]
    # … and the old citation still reads what was cited, by its commit.
    try:
        then = db.execute(
            f"SELECT chunk FROM kb_chunks AS OF COMMIT {int(cited['as_of'])} "
            "WHERE id = $1 AND position = $2",
            [cited["id"], cited["position"]],
        ).rows[0][0]
        print("the citation, read back:", then)
        assert then == cited["chunk"]
    except nucleus.Error as e:
        if e.code != "72000":
            raise
        print("(the history no longer holds that commit: start the server with --history 1h)")

    # 2. A memory per user: each sees only their own.
    db.remember("assistant_memory", "ann", "Ann prefers short answers", kind="preference")
    old, _ = db.remember("assistant_memory", "ann", "Ann lives in Szeged")
    db.remember("assistant_memory", "ann", "Ann moved to Pécs", replaces=old)  # the old fact kept as history
    db.remember("assistant_memory", "bob", "Bob wants every detail", kind="preference")
    db.execute("INSERT INTO tickets VALUES (1, 'ann', 'parcel lost'), (2, 'bob', 'late refund')")
    memories = db.recall("assistant_memory", "ann", "how should I answer, and where does she live")
    print("ann's memories:", [m["content"] for m in memories])
    assert {m["content"] for m in memories} == {"Ann prefers short answers", "Ann moved to Pécs"}

    # 3. What a reply read, recorded under its request id.
    request = f"reply-{os.getpid()}"
    db.execute(f"SET request_id = '{request}'")
    db.recall("assistant_memory", "ann", "how should I answer")
    search(db, "refund")
    db.execute("RESET request_id")
    for r in db.execute(
            "SELECT as_of, tables, array_length(ids, 1) AS n FROM nc_catalog.reads "
            "WHERE request_id = $1 ORDER BY at", [request]).records():
        print(request, "read:", r)

    # 4. Ann asks to be forgotten: her memories and tickets go, every file
    # is scrubbed of them and searched (found == 0 is the proof), the
    # records of what was read for her are blanked.  (A backup taken
    # before — BACKUP TO — sealed her rows under her key, which this
    # destroys: restored, it leaves her out.)
    erasure, rows, scrubbed, found = db.forget_subject("ann")
    print(f"erasure {erasure}: {rows} rows, scrubbed {scrubbed}, found {found}")
    assert rows == 4 and found in (0, None), (rows, found)
    left = db.recall("assistant_memory", "ann", "answer")
    assert left == [], left
    bob = db.recall("assistant_memory", "bob", "answer")
    assert [m["content"] for m in bob] == ["Bob wants every detail"], bob
    tickets = [r[0] for r in db.execute("SELECT customer FROM tickets").rows]
    assert tickets == ["bob"], tickets
    print("erasures:", db.execute("SELECT erasure, tables, rows FROM nc_catalog.erasures "
                                  "ORDER BY erasure DESC LIMIT 1").records())

    for t in ("kb_chunks", "kb_docs", "assistant_memory", "tickets"):
        db.execute(f"DROP TABLE {t}")
    db.execute("DROP MODEL words")
print("done")
