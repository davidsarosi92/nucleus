#!/usr/bin/env python3
"""Generate the Unicode tables of modules/local-models' tokenizers
(PLAN.md §M14.22 E3a).

    scripts/gen-tokenizer-tables.py bert 8.0.0 UnicodeData.txt > \
        modules/local-models/src/tokenizer/bert_tables.rs
    scripts/gen-tokenizer-tables.py graphemes GraphemeBreakProperty.txt \
        emoji-data.txt DerivedCoreProperties.txt > \
        modules/local-models/src/tokenizer/grapheme_breaks.rs

`bert` takes Unicode **8.0.0**'s UnicodeData.txt (which has no header:
the version is given before it): BERT's normalizer and
pre-tokenizer as Hugging Face's `tokenizers` runs them — what the models'
publishers and every runtime that loads `tokenizer.json` use — read
general categories from the `unicode_categories` crate, whose tables are
Unicode 8's, and decompose by that version too.  Checked against
`tokenizers` code point by code point (bench/embed/tokens.py), the
newer data differs on 560 code points, Unicode 8's on none.

`graphemes` takes the current version's files (16.0.0): the extended
grapheme clusters of UAX #29, which the SentencePiece normalizer works in.

The files come from https://www.unicode.org/Public/<version>/ucd/;
`graphemes` reads the version from their headers.
"""
import re
import sys

LICENSE = [
    "// do not edit.  Unicode data: Copyright (c) 1991-2024 Unicode, Inc.,",
    "// under the Unicode License v3 (https://www.unicode.org/license.txt).",
]


def ranges(path, want=None, field=1):
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = [p.strip() for p in line.split(";")]
        cps, prop = parts[0], parts[field]
        if want is not None and prop != want:
            continue
        lo, _, hi = cps.partition("..")
        yield int(lo, 16), int(hi or lo, 16), parts


def version(path):
    for line in open(path, encoding="utf-8"):
        m = re.match(r"#\s*\S+-(\d+\.\d+\.\d+)\.txt", line)
        if m:
            return m.group(1)
    return "?"


def runs(value):
    """(lo, hi, v) for the runs of equal nonzero values."""
    out = []
    start = 0
    for c in range(1, len(value) + 1):
        if c == len(value) or value[c] != value[start]:
            if value[start]:
                out.append((start, c - 1, value[start]))
            start = c
    return out


def unicode_data(path):
    """General category, canonical decomposition and combining class."""
    gc, dec, ccc = {}, {}, {}
    first = None
    for line in open(path, encoding="utf-8"):
        f = line.split(";")
        c = int(f[0], 16)
        if f[1].endswith("First>"):
            first = c
            continue
        span = range(first, c + 1) if f[1].endswith("Last>") else [c]
        for x in span:
            gc[x] = f[2]
            if int(f[3]):
                ccc[x] = int(f[3])
        if f[5] and not f[5].startswith("<"):
            dec[c] = [int(x, 16) for x in f[5].split()]
    return gc, dec, ccc


def bert(ver, path):
    gc, dec, ccc = unicode_data(path)
    # The normalizer's and pre-tokenizer's classes: 1 a control (removed:
    # Cc, Cf, Co — Cn is kept), 2 punctuation (split off: P*), 4 a
    # nonspacing mark (stripped with the accents: Mn).
    value = bytearray(0x110000)
    for c, g in gc.items():
        if g in ("Cc", "Cf", "Co"):
            value[c] |= 1
        if g.startswith("P"):
            value[c] |= 2
        if g == "Mn":
            value[c] |= 4
    classes = runs(value)

    def full(c):
        return [y for x in dec[c] for y in (full(x) if x in dec else [x])]

    flat, index = [], []
    for c in sorted(dec):
        d = full(c)
        index.append((c, len(flat), len(d)))
        flat.extend(d)
    cccv = bytearray(0x110000)
    for c, v in ccc.items():
        cccv[c] = v
    combining = runs(cccv)
    print("// Generated by scripts/gen-tokenizer-tables.py from the Unicode")
    print(f"// Character Database {ver} (UnicodeData.txt);")
    for line in LICENSE:
        print(line)
    print()
    print("/// Code-point ranges, ascending: 1 a control BERT's normalizer removes")
    print("/// (Cc, Cf, Co), 2 punctuation its pre-tokenizer splits off (P*), 4 a")
    print("/// nonspacing mark (Mn).")
    print("#[rustfmt::skip]")
    print(f"pub(super) static CLASSES: [(u32, u32, u8); {len(classes)}] = [")
    for lo, hi, v in classes:
        print(f"    (0x{lo:X}, 0x{hi:X}, {v}),")
    print("];")
    print()
    print("/// Canonical decompositions, fully applied: a code point, where its")
    print("/// code points start in [`DECOMPOSED`] and how many (Hangul syllables")
    print("/// are decomposed by arithmetic).")
    print("#[rustfmt::skip]")
    print(f"pub(super) static DECOMPOSITIONS: [(u32, u16, u8); {len(index)}] = [")
    for c, at, n in index:
        print(f"    (0x{c:X}, {at}, {n}),")
    print("];")
    print()
    print("#[rustfmt::skip]")
    print(f"pub(super) static DECOMPOSED: [u32; {len(flat)}] = [")
    for i in range(0, len(flat), 8):
        print("    " + " ".join(f"0x{x:X}," for x in flat[i:i + 8]))
    print("];")
    print()
    print("/// Canonical combining classes, the nonzero ones.")
    print("#[rustfmt::skip]")
    print(f"pub(super) static COMBINING: [(u32, u32, u8); {len(combining)}] = [")
    for lo, hi, v in combining:
        print(f"    (0x{lo:X}, 0x{hi:X}, {v}),")
    print("];")


# The order is `Gcb`'s in graphemes.rs.
GCB = [
    "Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
    "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT",
]
PICTOGRAPHIC = 0x10
INCB = {"Linker": 0x20, "Consonant": 0x40, "Extend": 0x60}


def graphemes(gcb, emoji, derived):
    value = bytearray(0x110000)
    for lo, hi, parts in ranges(gcb):
        for c in range(lo, hi + 1):
            value[c] = GCB.index(parts[1])
    for lo, hi, _ in ranges(emoji, "Extended_Pictographic"):
        for c in range(lo, hi + 1):
            value[c] |= PICTOGRAPHIC
    for lo, hi, parts in ranges(derived, "InCB"):
        for c in range(lo, hi + 1):
            value[c] |= INCB[parts[2]]
    out = runs(value)
    print("// Generated by scripts/gen-tokenizer-tables.py from the Unicode")
    print(f"// Character Database {version(gcb)} (GraphemeBreakProperty.txt,")
    print("// emoji-data.txt, DerivedCoreProperties.txt);")
    for line in LICENSE:
        print(line)
    print()
    print("/// Code-point ranges, ascending: the grapheme-cluster-break class in")
    print("/// the low four bits ([`super::graphemes::Gcb`]'s order), `0x10` where")
    print("/// the code point is Extended_Pictographic, and its Indic conjunct")
    print("/// break in bits 5 and 6 (1 Linker, 2 Consonant, 3 Extend).")
    print("#[rustfmt::skip]")
    print(f"pub(super) static RANGES: [(u32, u32, u8); {len(out)}] = [")
    for lo, hi, v in out:
        print(f"    (0x{lo:X}, 0x{hi:X}, {v}),")
    print("];")


if __name__ == "__main__":
    if sys.argv[1] == "bert":
        bert(sys.argv[2], sys.argv[3])
    elif sys.argv[1] == "graphemes":
        graphemes(sys.argv[2], sys.argv[3], sys.argv[4])
    else:
        sys.exit("bert VERSION UnicodeData.txt | graphemes GraphemeBreakProperty.txt emoji-data.txt DerivedCoreProperties.txt")
