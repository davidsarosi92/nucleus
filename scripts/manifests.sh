#!/usr/bin/env bash
# A release's Homebrew formula and winget manifests (PLAN.md §M14.17 E1),
# from its archives' SHA256SUMS:
#
#   scripts/manifests.sh <dist> [<download-url>]
#
# writes <dist>/nucleus.rb (for a tap: brew install <tap>/nucleus) and
# <dist>/winget/ (the three manifests winget-pkgs takes, under
# manifests/d/davidsarosi92/nucleus/<version>/).  Publishing them is the
# maintainer's: a commit to the tap, a pull request to winget-pkgs.
# <download-url> defaults to the release's on GitHub.
set -euo pipefail

dist=${1:?usage: scripts/manifests.sh <dist> [<download-url>]}
root=$(cd "$(dirname "$0")/.." && pwd)
version=$(sed -n 's/^version = "\(.*\)"/\1/p' "$root/Cargo.toml" | head -1)
repo=davidsarosi92/nucleus
url=${2:-https://github.com/$repo/releases/download/v$version}
sums="$dist/SHA256SUMS"
[ -f "$sums" ] || { echo "manifests.sh: no $sums" >&2; exit 1; }
summary="A database: SQL, documents, vectors and text search in one engine"

# The sum of the archive with this suffix ("" if the release has none).
sum() { sed -n "s/^\([0-9a-f]\{64\}\)  nucleus-$version$1\$/\1/p" "$sums" | head -1; }

# Homebrew: the macOS archives and Linux's static ones.
{
  cat <<RUBY
# The nucleus formula, generated by scripts/manifests.sh for $version.
class Nucleus < Formula
  desc "$summary"
  homepage "https://github.com/$repo"
  version "$version"
  license "AGPL-3.0-only"

RUBY
  for os in macos linux; do
    echo "  on_$os do"
    for arch in aarch64 x86_64; do
      if [ "$os" = linux ]; then suffix="-linux-$arch-musl.tar.gz"; else suffix="-macos-$arch.tar.gz"; fi
      s=$(sum "$suffix")
      [ -n "$s" ] || continue
      if [ "$arch" = aarch64 ]; then echo "    on_arm do"; else echo "    on_intel do"; fi
      echo "      url \"$url/nucleus-$version$suffix\""
      echo "      sha256 \"$s\""
      echo "    end"
    done
    echo "  end"
    echo
  done
  cat <<'RUBY'
  def install
    bin.install "bin/nucleus", "bin/ncsql"
  end

  test do
    assert_match "hello", shell_output("#{bin}/nucleus sql :memory: -c \"SELECT 'hello'\"")
  end
end
RUBY
} > "$dist/nucleus.rb"
echo "$dist/nucleus.rb"

# winget: the zip, its two programs as portable commands.
win=$(sum "-windows-x86_64.zip")
if [ -n "$win" ]; then
  id=davidsarosi92.nucleus
  out="$dist/winget"
  mkdir -p "$out"
  head="# Generated by scripts/manifests.sh for $version.
PackageIdentifier: $id
PackageVersion: $version"
  cat > "$out/$id.yaml" <<YAML
$head
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
YAML
  cat > "$out/$id.installer.yaml" <<YAML
$head
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: nucleus-$version\\bin\\nucleus.exe
    PortableCommandAlias: nucleus
  - RelativeFilePath: nucleus-$version\\bin\\ncsql.exe
    PortableCommandAlias: ncsql
Installers:
  - Architecture: x64
    InstallerUrl: $url/nucleus-$version-windows-x86_64.zip
    InstallerSha256: $(printf '%s' "$win" | tr 'a-f' 'A-F')
ManifestType: installer
ManifestVersion: 1.6.0
YAML
  cat > "$out/$id.locale.en-US.yaml" <<YAML
$head
PackageLocale: en-US
Publisher: davidsarosi92
PackageName: nucleus
PackageUrl: https://github.com/$repo
License: AGPL-3.0-only
LicenseUrl: https://github.com/$repo/blob/main/COPYRIGHT
ShortDescription: $summary
Moniker: nucleus
Tags:
  - database
  - sql
ManifestType: defaultLocale
ManifestVersion: 1.6.0
YAML
  echo "$out/"
fi
