#!/usr/bin/env python3
"""Generate crates/sql/src/text/word_breaks.rs: the Unicode word-break
property (UAX #29) and Extended_Pictographic as sorted code-point ranges.

    scripts/gen-word-breaks.py WordBreakProperty.txt emoji-data.txt > \
        crates/sql/src/text/word_breaks.rs

Both files come from https://www.unicode.org/Public/<version>/ucd/
(auxiliary/ and emoji/); the version is read from their headers.
"""
import re
import sys

# The order is the `Break` enum's in word_breaks.rs (and words.rs).
CLASSES = [
    "Other", "CR", "LF", "Newline", "Extend", "ZWJ", "Regional_Indicator",
    "Format", "Katakana", "Hebrew_Letter", "ALetter", "Single_Quote",
    "Double_Quote", "MidNumLet", "MidLetter", "MidNum", "Numeric",
    "ExtendNumLet", "WSegSpace",
]
PICTOGRAPHIC = 0x20  # a flag beside the class


def ranges(path, want=None):
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, prop = [p.strip() for p in line.split(";")[:2]]
        if want is not None and prop != want:
            continue
        lo, _, hi = cps.partition("..")
        yield int(lo, 16), int(hi or lo, 16), prop


def version(path):
    for line in open(path, encoding="utf-8"):
        m = re.match(r"#\s*\S+-(\d+\.\d+\.\d+)\.txt", line)
        if m:
            return m.group(1)
    return "?"


def main(words, emoji):
    value = bytearray(0x110000)
    for lo, hi, prop in ranges(words):
        for c in range(lo, hi + 1):
            value[c] = CLASSES.index(prop)
    for lo, hi, _ in ranges(emoji, "Extended_Pictographic"):
        for c in range(lo, hi + 1):
            value[c] |= PICTOGRAPHIC
    out = []
    start = 0
    for c in range(1, 0x110001):
        if c == 0x110000 or value[c] != value[start]:
            if value[start]:
                out.append((start, c - 1, value[start]))
            start = c
    print("// Generated by scripts/gen-word-breaks.py from the Unicode Character")
    print(f"// Database {version(words)} (WordBreakProperty.txt, emoji-data.txt);")
    print("// do not edit.  Unicode data: Copyright (c) 1991-2024 Unicode, Inc.,")
    print("// under the Unicode License v3 (https://www.unicode.org/license.txt).")
    print()
    print("/// Code-point ranges, ascending, with their word-break class (the low")
    print("/// five bits, [`super::words::Break`]'s order) and `0x20` where the code")
    print("/// point is Extended_Pictographic; every other code point is `Other`.")
    print("#[rustfmt::skip]")
    print(f"pub(crate) static RANGES: [(u32, u32, u8); {len(out)}] = [")
    for lo, hi, v in out:
        print(f"    (0x{lo:X}, 0x{hi:X}, {v}),")
    print("];")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
