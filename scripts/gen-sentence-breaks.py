#!/usr/bin/env python3
"""Generate crates/sql/src/text/sentence_breaks.rs: the Unicode
sentence-break property (UAX #29) as sorted code-point ranges, and
crates/sql/tests/data/sentence_break_test.txt: Unicode's own test cases
without their comments.

    scripts/gen-sentence-breaks.py SentenceBreakProperty.txt SentenceBreakTest.txt

Both files come from https://www.unicode.org/Public/<version>/ucd/auxiliary/;
the version is read from their headers.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The order is the `Break` enum's in sentences.rs.
CLASSES = [
    "Other", "CR", "LF", "Extend", "Sep", "Format", "Sp", "Lower", "Upper",
    "OLetter", "Numeric", "ATerm", "SContinue", "STerm", "Close",
]


def ranges(path):
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, prop = [p.strip() for p in line.split(";")[:2]]
        lo, _, hi = cps.partition("..")
        yield int(lo, 16), int(hi or lo, 16), prop


def version(path):
    for line in open(path, encoding="utf-8"):
        m = re.match(r"#\s*\S+-(\d+\.\d+\.\d+)\.txt", line)
        if m:
            return m.group(1)
    return "?"


def table(prop_path):
    value = bytearray(0x110000)
    for lo, hi, prop in ranges(prop_path):
        for c in range(lo, hi + 1):
            value[c] = CLASSES.index(prop)
    out = []
    start = 0
    for c in range(1, 0x110001):
        if c == 0x110000 or value[c] != value[start]:
            if value[start]:
                out.append((start, c - 1, value[start]))
            start = c
    lines = [
        "// Generated by scripts/gen-sentence-breaks.py from the Unicode Character",
        f"// Database {version(prop_path)} (SentenceBreakProperty.txt); do not edit.",
        "// Unicode data: Copyright (c) 1991-2024 Unicode, Inc., under the Unicode",
        "// License v3 (https://www.unicode.org/license.txt).",
        "",
        "/// Code-point ranges, ascending, with their sentence-break class",
        "/// ([`super::sentences::Break`]'s order); every other code point is",
        "/// `Other`.",
        "#[rustfmt::skip]",
        f"pub(crate) static RANGES: [(u32, u32, u8); {len(out)}] = [",
    ]
    lines += [f"    (0x{lo:X}, 0x{hi:X}, {v})," for lo, hi, v in out]
    lines.append("];")
    return "\n".join(lines) + "\n"


def cases(test_path):
    lines = [
        "# UAX #29 sentence-break test cases, comments removed, from the Unicode",
        f"# Character Database {version(test_path)} (auxiliary/SentenceBreakTest.txt).",
        "# Copyright (c) 1991-2024 Unicode, Inc.; Unicode License v3",
        "# (https://www.unicode.org/license.txt).",
    ]
    for line in open(test_path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if line:
            lines.append(line)
    return "\n".join(lines) + "\n"


def main(prop_path, test_path):
    with open(os.path.join(ROOT, "crates/sql/src/text/sentence_breaks.rs"), "w") as f:
        f.write(table(prop_path))
    with open(os.path.join(ROOT, "crates/sql/tests/data/sentence_break_test.txt"), "w") as f:
        f.write(cases(test_path))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
