#!/usr/bin/env python3
"""Generate crates/sql/src/text/stop_words.rs from Snowball's stop-word
lists (https://snowballstem.org, BSD licence):

    scripts/gen-stop-words.py DIR > crates/sql/src/text/stop_words.rs

DIR holds <language>.txt as the Snowball website has them
(algorithms/<language>/stop.txt): words before `|`, the rest comments.
"""
import os
import sys

LANGUAGES = [
    "danish", "dutch", "english", "finnish", "french", "german", "hungarian",
    "italian", "norwegian", "portuguese", "russian", "spanish", "swedish",
]


def words(path):
    out = set()
    for line in open(path, encoding="utf-8"):
        for w in line.split("|", 1)[0].split():
            out.add(w.lower())
    # Byte order: what `<[&str]>::binary_search` compares by.
    return sorted(out, key=lambda w: w.encode("utf-8"))


def main(d):
    print("// Generated by scripts/gen-stop-words.py from Snowball's stop-word")
    print("// lists (https://snowballstem.org); do not edit.  Copyright (c) 2001,")
    print("// Dr Martin Porter, and the Snowball contributors; BSD 3-clause licence")
    print("// (https://snowballstem.org/license.html).")
    print()
    print("/// Each language's stop words, sorted by their bytes.")
    print("#[rustfmt::skip]")
    print(f"pub(crate) static LISTS: [(&str, &[&str]); {len(LANGUAGES)}] = [")
    for lang in LANGUAGES:
        ws = words(os.path.join(d, lang + ".txt"))
        print(f"    (\"{lang}\", &[")
        line = "       "
        for w in ws:
            item = f" \"{w}\","
            if len(line) + len(item) > 78:
                print(line)
                line = "       "
            line += item
        print(line)
        print("    ]),")
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
