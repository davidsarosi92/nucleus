//! Memory stores (PLAN.md §M14.24 R1): memories for AI models as rows.
//!
//! `CREATE MEMORY STORE notes USING m` makes a table of known columns —
//! whose memory (`subject`), what kind, its text, an embedding column by
//! `m`, a confidence, how often it was seen, when it held (`valid_from`,
//! `valid_to`: valid time, as Zep / Graphiti keep it; the transaction
//! time is the engine's), when it expires, where it came from and what it
//! replaced — with an index on the subject, an HNSW index (cosine) on the
//! vectors and a text index on the texts, and its rows expiring by
//! `expires_at` ([`crate::expiry`]).
//!
//! `REMEMBER text FOR subject IN notes` keeps a memory: merged into a
//! current one of the same subject with the same text, or whose vector's
//! cosine similarity is at least the store's `merge` (its `seen` counted,
//! its confidence the greater) — else added.  `REPLACING id` closes the
//! memory it replaces (its `valid_to` now, kept as history) and adds the
//! new one.  Whether a new fact contradicts an old one is the model's
//! judgement, not the database's: the caller says what it replaces.
//! Everything runs as ordinary SQL in the caller's transaction, under
//! its privileges and row-level security — a merge never reaches a row
//! the caller may not see.
//!
//! `recall('notes', subject, query [, k])` in `FROM` is bound as a query
//! ([`recall_query`]): the subject's current, unexpired memories ranked
//! by reciprocal rank fusion of BM25 over the texts and the vectors'
//! nearness to the query's (§8.20), the best `k` (10).

use std::sync::{Arc, OnceLock};

use nucleus_kv::KvTxn;

use crate::ast::{self, Statement};
use crate::catalog::{self, MemorySpec, Table};
use crate::error::{Error, Result};
use crate::ext::Registry;
use crate::types::{DataType, Value};

/// The names of `REMEMBER`'s result columns: the memory's id (a `uuid`)
/// and what was done.
pub const RESULT: [&str; 2] = ["id", "action"];

/// The default similarity at which `REMEMBER` merges.
pub const DEFAULT_MERGE: f64 = 0.95;

fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('"', "\"\""))
}

fn literal(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

/// `CREATE MEMORY STORE name USING model [WITH (merge = x, analyzer =
/// a)]`, in `txn`.
pub(crate) fn create(
    txn: &mut dyn KvTxn,
    reg: &Registry,
    name: &str,
    model: &str,
    options: &[(String, String)],
) -> Result<()> {
    let mut merge = DEFAULT_MERGE;
    let mut analyzer = crate::text::DEFAULT.to_string();
    for (k, v) in options {
        match k.as_str() {
            "merge" => {
                merge = v
                    .parse::<f64>()
                    .ok()
                    .filter(|m| (0.0..=1.0).contains(m))
                    .ok_or_else(|| {
                        Error::invalid_parameter(format!(
                            "merge is a cosine similarity from 0 to 1, not {v}"
                        ))
                    })?;
            }
            "analyzer" => analyzer = v.clone(),
            _ => {
                return Err(Error::invalid_parameter(format!(
                    "unrecognized memory store option \"{k}\" (merge, analyzer)"
                )));
            }
        }
    }
    let t = quote(name);
    let statements = [
        format!(
            "CREATE TABLE {t} (\
             id uuid PRIMARY KEY DEFAULT uuidv7(), \
             subject text NOT NULL, \
             kind text NOT NULL DEFAULT 'fact', \
             content text NOT NULL, \
             embedding vector GENERATED BY EMBEDDING (content) USING {}, \
             confidence real NOT NULL DEFAULT 1, \
             seen integer NOT NULL DEFAULT 1, \
             valid_from timestamptz NOT NULL DEFAULT now(), \
             valid_to timestamptz, \
             expires_at timestamptz, \
             source text, \
             replaces uuid, \
             created timestamptz NOT NULL DEFAULT now(), \
             last_seen timestamptz NOT NULL DEFAULT now())",
            quote(model)
        ),
        format!(
            "CREATE INDEX {} ON {t} (subject)",
            quote(&format!("{name}_subject"))
        ),
        format!(
            "CREATE INDEX {} ON {t} USING hnsw (embedding vector_cosine_ops)",
            quote(&format!("{name}_embedding"))
        ),
        format!(
            "CREATE INDEX {} ON {t} USING text (content) WITH (analyzer = {})",
            quote(&format!("{name}_content")),
            literal(&analyzer)
        ),
    ];
    for sql in statements {
        let stmt = crate::parser::parse(&sql)?.remove(0);
        crate::session::execute_statement(
            txn,
            reg,
            &stmt,
            &[],
            &mut crate::session::Collect::default(),
        )?;
    }
    let mut table = catalog::table(&*txn, name)?;
    table.expiry = table.column("expires_at");
    table.memory = Some(MemorySpec {
        model: model.to_string(),
        merge,
    });
    catalog::update_table(txn, &table)
}

/// Table `name`, which must be a memory store.
pub(crate) fn store(txn: &dyn KvTxn, name: &str) -> Result<(Table, MemorySpec)> {
    let t = catalog::table(txn, name)?;
    match t.memory.clone() {
        Some(m) => Ok((t, m)),
        None => Err(Error::wrong_object_type(format!(
            "\"{name}\" is not a memory store (CREATE MEMORY STORE)"
        ))),
    }
}

/// The condition of a store's current memories.
const CURRENT: &str = "valid_to IS NULL AND (expires_at IS NULL OR expires_at > now())";

/// The query `recall(store, subject, query [, k])` is bound as: its
/// parameters `$1` the subject, `$2` the query text, `$3` how many.
pub(crate) fn recall_query(txn: &dyn KvTxn, name: &str) -> Result<ast::Query> {
    store(txn, name)?;
    let sql = format!(
        "SELECT id, kind, content, confidence, seen, valid_from, source, created, last_seen, \
         rrf(score(content @@ $2), embedding <=> embed($2)) AS score \
         FROM {} WHERE subject = $1 AND {CURRENT} \
         ORDER BY rrf(score(content @@ $2), embedding <=> embed($2)) DESC LIMIT $3",
        quote(name)
    );
    match crate::parser::parse(&sql)?.remove(0) {
        Statement::Query(q) => Ok(q),
        _ => Err(Error::internal("recall's query")),
    }
}

/// The statements `REMEMBER` runs, for a store: parsed once a store name.
struct Plans {
    /// `$1` subject, `$2` content: a current memory with the same text.
    same: Statement,
    /// `$1` subject, `$2` vector: the nearest current memory, its
    /// distance.
    nearest: Statement,
    /// `$1` subject, `$2` vector: the subject's current memories whose
    /// vectors the queue has not made yet, each one's distance — its
    /// text embedded here (the model's cache has it: `REMEMBER` embedded
    /// it), so a merge does not depend on the queue's pace.
    pending: Statement,
    /// `$1` id, `$2` confidence: a merge.
    merge: Statement,
    /// `$1` id, `$2` subject: the replaced memory closed.
    close: Statement,
    /// The memory added: `$1` subject … `$8` replaces.
    add: Statement,
}

fn plans(name: &str, model: &str) -> Result<Arc<Plans>> {
    type Kept = std::collections::HashMap<(String, String), Arc<Plans>>;
    static KEPT: OnceLock<std::sync::Mutex<Kept>> = OnceLock::new();
    let kept = KEPT.get_or_init(Default::default);
    let key = (name.to_string(), model.to_string());
    if let Some(p) = kept.lock().unwrap().get(&key) {
        return Ok(Arc::clone(p));
    }
    let t = quote(name);
    let one = |sql: String| -> Result<Statement> { Ok(crate::parser::parse(&sql)?.remove(0)) };
    let p = Arc::new(Plans {
        same: one(format!(
            "SELECT id FROM {t} WHERE subject = $1 AND content = $2 AND {CURRENT} LIMIT 1"
        ))?,
        nearest: one(format!(
            "SELECT id, embedding <=> $2 FROM {t} WHERE subject = $1 AND {CURRENT} \
             ORDER BY embedding <=> $2 LIMIT 1"
        ))?,
        pending: one(format!(
            "SELECT id, embed(content, {}, 'document') <=> $2 FROM {t} \
             WHERE subject = $1 AND embedding IS NULL AND {CURRENT}",
            literal(model)
        ))?,
        merge: one(format!(
            "UPDATE {t} SET seen = seen + 1, last_seen = now(), \
             confidence = greatest(confidence, coalesce($2, confidence)) WHERE id = $1"
        ))?,
        close: one(format!(
            "UPDATE {t} SET valid_to = now() WHERE id = $1 AND subject = $2 AND valid_to IS NULL \
             RETURNING id"
        ))?,
        add: one(format!(
            "INSERT INTO {t} (subject, content, kind, confidence, valid_from, expires_at, source, replaces) \
             VALUES ($1, $2, coalesce($3, 'fact'), coalesce(CAST($4 AS real), 1), \
             coalesce(CAST($5 AS timestamptz), now()), CAST($6 AS timestamptz), $7, $8) \
             RETURNING id"
        ))?,
    });
    let mut kept = kept.lock().unwrap();
    if kept.len() > 256 {
        kept.clear();
    }
    kept.insert(key, Arc::clone(&p));
    Ok(p)
}

/// The clauses of a `REMEMBER`, as one query of casts: its values, and
/// its parameters' types for a description.
pub(crate) fn clauses(r: &ast::Remember) -> ast::Query {
    let cast = |e: &Option<ast::Expr>, ty: ast::SqlType| -> ast::SelectItem {
        let expr = match e {
            Some(e) => e.clone(),
            None => ast::Expr::Literal(Value::Null),
        };
        ast::SelectItem::Expr {
            expr: ast::Expr::Cast {
                expr: Box::new(expr),
                ty,
                typmod: ast::TypeMod::default(),
            },
            alias: None,
        }
    };
    let b = ast::SqlType::builtin;
    let items = vec![
        cast(&Some(r.subject.clone()), b(DataType::Text)),
        cast(&Some(r.content.clone()), b(DataType::Text)),
        cast(&r.kind, b(DataType::Text)),
        cast(&r.confidence, b(DataType::Real)),
        cast(&r.valid_from, b(DataType::TimestampTz)),
        cast(&r.expires, b(DataType::TimestampTz)),
        cast(&r.source, b(DataType::Text)),
        cast(
            &r.replacing,
            ast::SqlType::Named {
                schema: None,
                name: "uuid".into(),
            },
        ),
    ];
    ast::Query {
        with: None,
        body: ast::SetExpr::Select(Box::new(ast::Select {
            distinct: false,
            items,
            from: vec![],
            filter: None,
            group_by: vec![],
            having: None,
            windows: vec![],
        })),
        order_by: vec![],
        limit: None,
        offset: None,
    }
}

/// Runs `stmt` with `params`; its rows.
fn rows(
    txn: &mut dyn KvTxn,
    reg: &Registry,
    stmt: &Statement,
    params: &[Value],
) -> Result<Vec<Vec<Value>>> {
    let mut all = crate::session::Collect::default();
    let out = crate::session::execute_statement(txn, reg, stmt, params, &mut all)?;
    Ok(match out {
        crate::session::Output::Rows { rows, .. } => rows,
        crate::session::Output::Command(_) => all.rows,
    })
}

/// `REMEMBER …`, in `txn`: the memory's id, what was done (`inserted`,
/// `merged`, `replaced`) and the id's type.
pub(crate) fn remember(
    txn: &mut dyn KvTxn,
    reg: &Registry,
    r: &ast::Remember,
    params: &[Value],
) -> Result<(Value, &'static str, DataType)> {
    let (table, spec) = store(&*txn, &r.store)?;
    let id_type = table.columns[0].ty;
    let values = rows(txn, reg, &Statement::Query(clauses(r)), params)?
        .pop()
        .ok_or_else(|| Error::internal("REMEMBER's clauses"))?;
    let [
        subject,
        content,
        kind,
        confidence,
        valid_from,
        expires,
        source,
        replacing,
    ]: [Value; 8] = values
        .try_into()
        .map_err(|_| Error::internal("REMEMBER's clauses"))?;
    if subject == Value::Null || content == Value::Null {
        return Err(Error::not_null_violation(
            "REMEMBER needs a text and a subject, not NULL",
        ));
    }
    let p = plans(&r.store, &spec.model)?;
    if replacing != Value::Null {
        if rows(txn, reg, &p.close, &[replacing.clone(), subject.clone()])?.is_empty() {
            return Err(Error::undefined_object(format!(
                "no current memory {replacing} of this subject in \"{}\" to replace",
                r.store
            )));
        }
    } else {
        // The same text, current: merged (whether or not its vector is
        // made yet).
        if let Some(row) = rows(txn, reg, &p.same, &[subject.clone(), content.clone()])?.pop() {
            rows(txn, reg, &p.merge, &[row[0].clone(), confidence.clone()])?;
            return Ok((row[0].clone(), "merged", id_type));
        }
        // A near-identical one, by the store's model.
        let embed = crate::parser::parse(&format!(
            "SELECT embed($1, {}, 'document')",
            literal(&spec.model)
        ))?
        .remove(0);
        let vector = rows(txn, reg, &embed, std::slice::from_ref(&content))?
            .pop()
            .and_then(|mut r| r.pop())
            .unwrap_or(Value::Null);
        if vector != Value::Null {
            let args = [subject.clone(), vector];
            let mut found = rows(txn, reg, &p.nearest, &args)?;
            found.extend(rows(txn, reg, &p.pending, &args)?);
            let best = found
                .into_iter()
                .filter_map(|r| match r[1] {
                    Value::Float(d) => Some((d, r[0].clone())),
                    _ => None,
                })
                .min_by(|a, b| a.0.total_cmp(&b.0));
            if let Some((d, id)) = best
                && 1.0 - d >= spec.merge
            {
                rows(txn, reg, &p.merge, &[id.clone(), confidence.clone()])?;
                return Ok((id, "merged", id_type));
            }
        }
    }
    let id = rows(
        txn,
        reg,
        &p.add,
        &[
            subject,
            content,
            kind,
            confidence,
            valid_from,
            expires,
            source,
            replacing.clone(),
        ],
    )?
    .pop()
    .and_then(|mut r| r.pop())
    .ok_or_else(|| Error::internal("REMEMBER's insert returned no id"))?;
    let action = if replacing == Value::Null {
        "inserted"
    } else {
        "replaced"
    };
    Ok((id, action, id_type))
}
