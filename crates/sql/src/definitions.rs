//! The schema as the SQL that makes it: `nc_catalog.definitions` (PLAN.md
//! §M14.16 M1).
//!
//! Every schema object's creating statement, written from the catalog's
//! own records — not text kept from when it was made, so a table altered
//! twenty times is one `CREATE TABLE` — in an order that replays on an
//! empty database: models, enum types and what types were taught; tables
//! (ordinary ones, then partitions, memory stores, chunk tables and
//! collections, each after what it is made from) with their columns, keys, unique
//! constraints and checks; then indexes, statistics objects, foreign keys
//! (after every table, so cycles need no order), comments, the tables'
//! settings (storage, expiry, subjects, row security) and policies.
//!
//! The law ([`tests`] and `crates/sql/tests/definitions.rs`): a schema's
//! definitions run on an empty database give the same definitions.
//!
//! Not here: roles, grants and ownership (who may, not what is — as
//! `pg_dump`'s `--no-owner --no-acl`), secrets (their values are never
//! shown: a model that names one needs it made first), access rules,
//! tokens, database settings, and data.

use std::collections::HashMap;

use nucleus_kv::KvTxn;

use crate::ast::{FkAction, Generated};
use crate::catalog::{self, Column, Index, Table};
use crate::error::Result;
use crate::ncatalog::type_text;

/// One object's creating statement.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Definition {
    /// What it makes: `model`, `type`, `ordering`, `operator`, `cast`,
    /// `table`, `partition`, `memory store`, `chunk table`, `collection`,
    /// `column`,
    /// `constraint`, `index`, `statistics`, `foreign key`, `comment`,
    /// `storage`, `expiry`, `subject`, `row security`, `policy`.
    pub kind: &'static str,
    /// The object's name (a column's, a constraint's, …; a comment's
    /// object).
    pub name: String,
    /// The table it belongs to, if any.
    pub table: Option<String>,
    /// The statement, without its `;`.
    pub sql: String,
}

/// `name` as an identifier: bare when it reads back as itself (lower
/// case, not a reserved word), else in double quotes.
pub fn ident(name: &str) -> String {
    let mut chars = name.chars();
    let bare = chars
        .next()
        .is_some_and(|c| c.is_ascii_lowercase() || c == '_')
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && !crate::parser::is_reserved(name);
    if bare {
        name.to_string()
    } else {
        format!("\"{}\"", name.replace('"', "\"\""))
    }
}

/// `s` as a string literal.
pub fn literal(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

fn list(t: &Table, cols: &[usize]) -> String {
    cols.iter()
        .map(|&c| ident(&t.columns[c].name))
        .collect::<Vec<_>>()
        .join(", ")
}

/// A column as `CREATE TABLE` and `ADD COLUMN` write it.
pub fn column_sql(c: &Column) -> String {
    column_sql_with(c, &HashMap::new())
}

/// [`column_sql`], an identity column's sequence's options (`options`,
/// by the sequence's name) in its parentheses.
fn column_sql_with(c: &Column, options: &HashMap<String, String>) -> String {
    let mut s = format!("{} {}", ident(&c.name), type_text(c));
    if !c.nullable && c.identity.is_none() {
        s.push_str(" NOT NULL");
    }
    if let Some(i) = &c.identity {
        s.push_str(&format!(
            " GENERATED {} AS IDENTITY (SEQUENCE NAME {}{})",
            if i.always { "ALWAYS" } else { "BY DEFAULT" },
            ident(&i.sequence),
            options.get(&i.sequence).map_or("", String::as_str)
        ));
    } else if let Some(d) = &c.default {
        s.push_str(&format!(" DEFAULT {d}"));
    }
    match &c.generated {
        Some(Generated::Stored(e)) => s.push_str(&format!(" GENERATED ALWAYS AS ({e}) STORED")),
        Some(Generated::Embedding { source, model, .. }) => s.push_str(&format!(
            " GENERATED BY EMBEDDING ({source}) USING {}",
            ident(model)
        )),
        None => {}
    }
    s
}

/// An option's value as `WITH (…)` takes it back: a number or a word
/// bare, anything else a string (the option keeps the text either way).
fn option_value(v: &str) -> String {
    let number = !v.is_empty()
        && v.parse::<f64>().is_ok()
        && v.chars().all(|c| c.is_ascii_digit() || c == '.');
    if number || ident(v) == v {
        v.to_string()
    } else {
        literal(v)
    }
}

fn with(options: &[(String, String)]) -> String {
    if options.is_empty() {
        return String::new();
    }
    format!(
        " WITH ({})",
        options
            .iter()
            .map(|(k, v)| format!("{} = {}", ident(k), option_value(v)))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

/// An index as `CREATE INDEX` writes it.
pub fn index_sql(t: &Table, ix: &Index) -> String {
    let parts = (0..ix.columns.len())
        .map(|k| {
            let mut p = match &ix.exprs[k] {
                Some(e) => format!("({})", e.sql),
                None => ident(&t.columns[ix.columns[k]].name),
            };
            if let Some(o) = &ix.orderings[k] {
                p.push_str(&format!(" USING {}", ident(o)));
            }
            if let Some(o) = &ix.opclasses[k] {
                p.push_str(&format!(" {}", ident(o)));
            }
            p
        })
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "CREATE {}INDEX {} ON {}{} ({parts}){}",
        if ix.unique { "UNIQUE " } else { "" },
        ident(&ix.name),
        ident(&t.name),
        ix.method
            .as_deref()
            .map_or(String::new(), |m| format!(" USING {}", ident(m))),
        with(&ix.options)
    )
}

fn fk_action(what: &str, a: FkAction) -> String {
    if a == FkAction::NoAction {
        String::new()
    } else {
        format!(" ON {what} {}", a.sql())
    }
}

/// What a table is, for the statement that makes it.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Shape {
    Plain,
    Partition,
    Memory,
    Chunks,
    Collection,
    Stream,
}

fn shape(t: &Table) -> Shape {
    if t.partition_of.is_some() {
        Shape::Partition
    } else if t.memory.is_some() {
        Shape::Memory
    } else if t.chunks.is_some() {
        Shape::Chunks
    } else if t.collection {
        Shape::Collection
    } else if crate::stream::is_stream(t) {
        Shape::Stream
    } else {
        Shape::Plain
    }
}

/// The memory store's own columns and indexes (`crate::memory::create`):
/// the first 14 columns and three indexes.
pub(crate) const MEMORY_COLUMNS: usize = 14;
fn memory_index(t: &Table, ix: &Index) -> bool {
    ["subject", "embedding", "content"]
        .iter()
        .any(|s| ix.name == format!("{}_{s}", t.name))
}

/// Whether column `c` is one the table's making statement makes (a
/// partition's are its parent's).
fn made_column(t: &Table, c: usize) -> bool {
    match shape(t) {
        Shape::Plain => true,
        Shape::Partition => true,
        Shape::Memory => c < MEMORY_COLUMNS,
        Shape::Chunks => crate::chunk_tables::derives(t, c),
        Shape::Collection => c < 2,
        Shape::Stream => true,
    }
}

/// Every definition of the database `txn` reads, in an order that
/// replays.
pub fn all(txn: &dyn KvTxn) -> Result<Vec<Definition>> {
    let tables = catalog::tables(txn)?;
    let mut out = Vec::new();
    let mut def = |kind: &'static str, name: &str, table: Option<&str>, sql: String| {
        out.push(Definition {
            kind,
            name: name.to_string(),
            table: table.map(str::to_string),
            sql,
        });
    };

    // Models: the columns and stores that use them come after.
    for m in crate::models::all(txn)? {
        let mut options = m.options.0.clone();
        for (k, v) in [
            ("secret", &m.secret),
            ("query_prefix", &m.query_prefix),
            ("document_prefix", &m.document_prefix),
        ] {
            if let Some(v) = v {
                options.push((k.to_string(), v.clone()));
            }
        }
        for k in crate::models::LIMITS {
            let n = m.limits.get(k);
            if n != 0 {
                options.push((k.to_string(), n.to_string()));
            }
        }
        def(
            "model",
            &m.name,
            None,
            format!(
                "CREATE MODEL {} USING {}{}",
                ident(&m.name),
                ident(&m.provider),
                with(&options)
            ),
        );
    }

    // Sequences (before the tables whose defaults call them; `OWNED BY`
    // after them) — an identity column's is the column's.
    let sequences = crate::sequences::all(txn)?;
    let identities: HashMap<String, String> = sequences
        .iter()
        .filter(|s| {
            tables.iter().any(|t| {
                t.columns
                    .iter()
                    .any(|c| c.identity.as_ref().is_some_and(|i| i.sequence == s.name))
            })
        })
        .map(|s| (s.name.clone(), crate::sequences::options_sql(s)))
        .collect();
    for s in &sequences {
        if !identities.contains_key(&s.name) {
            def("sequence", &s.name, None, crate::sequences::definition(s));
        }
    }

    // Types: enums, then what types were taught.
    for e in crate::enums::all(txn)? {
        let labels = e
            .labels
            .iter()
            .map(|(_, l)| literal(l))
            .collect::<Vec<_>>()
            .join(", ");
        def(
            "type",
            &e.name,
            None,
            format!("CREATE TYPE {} AS ENUM ({labels})", ident(&e.name)),
        );
    }
    for o in catalog::orderings(txn)? {
        def(
            "ordering",
            &o.name,
            None,
            format!(
                "ALTER TYPE {} ADD ORDERING {} BY {}",
                ident(&o.type_name),
                ident(&o.name),
                o.mapping
            ),
        );
    }
    for o in catalog::operators(txn)? {
        def(
            "operator",
            &o.symbol,
            None,
            format!(
                "ALTER TYPE {} ADD OPERATOR {} ({}, {}) AS {}",
                ident(&o.left),
                o.symbol,
                o.left,
                o.right,
                ident(&o.function)
            ),
        );
    }
    for c in catalog::casts(txn)? {
        def(
            "cast",
            &format!("{} to {}", c.from, c.to),
            None,
            format!(
                "ALTER TYPE {} ADD CAST TO {} AS {} {}",
                ident(&c.from),
                c.to,
                ident(&c.function),
                c.context.sql().to_ascii_uppercase()
            ),
        );
    }

    // Tables: ordinary ones (with partitioned ones), then partitions,
    // memory stores and chunk tables (each after its source).
    let by_shape = |s: Shape| tables.iter().filter(move |t| shape(t) == s);
    for t in by_shape(Shape::Plain) {
        let mut parts: Vec<String> = t
            .columns
            .iter()
            .map(|c| column_sql_with(c, &identities))
            .collect();
        for c in catalog::constraints(std::slice::from_ref(t)) {
            if matches!(c.kind, catalog::ConstraintKind::ForeignKey(_)) {
                continue;
            }
            parts.push(format!("CONSTRAINT {} {}", ident(&c.name), c.definition));
        }
        let mut sql = format!("CREATE TABLE {} ({})", ident(&t.name), parts.join(", "));
        if let Some(spec) = &t.partition_by {
            let kind = match spec.kind {
                crate::partition::Kind::Range => "RANGE",
                crate::partition::Kind::List => "LIST",
                crate::partition::Kind::Hash => "HASH",
            };
            sql.push_str(&format!(
                " PARTITION BY {kind} ({})",
                list(t, &spec.columns)
            ));
        }
        if t.storage != crate::storage::ROW && t.storage != crate::column_store::ROW_COLUMN {
            sql.push_str(&with(&[("storage".into(), t.storage.clone())]));
        }
        def("table", &t.name, Some(&t.name), sql);
    }
    for t in by_shape(Shape::Partition) {
        let (parent, bound) = t.partition_of.as_ref().expect("a partition");
        let mut sql = format!(
            "CREATE TABLE {} PARTITION OF {} {}",
            ident(&t.name),
            ident(parent),
            bound.render()
        );
        if t.storage != crate::storage::ROW && t.storage != crate::column_store::ROW_COLUMN {
            sql.push_str(&with(&[("storage".into(), t.storage.clone())]));
        }
        def("partition", &t.name, Some(&t.name), sql);
    }
    for t in by_shape(Shape::Memory) {
        let spec = t.memory.as_ref().expect("a memory store");
        let mut options = Vec::new();
        if spec.merge != crate::memory::DEFAULT_MERGE {
            options.push(("merge".to_string(), spec.merge.to_string()));
        }
        let content = format!("{}_content", t.name);
        if let Some(a) = t
            .indexes
            .iter()
            .find(|ix| ix.name == content)
            .and_then(|ix| ix.options.iter().find(|(k, _)| k == "analyzer"))
            .filter(|(_, a)| a != crate::text::DEFAULT)
        {
            options.push(a.clone());
        }
        if let Some(a) = spec
            .analyzer
            .as_ref()
            .filter(|a| *a != crate::text::DEFAULT)
        {
            options.push(("analyzer".to_string(), a.clone()));
        }
        if t.storage == crate::sealed::SEALED {
            options.push(("sealed".to_string(), "true".to_string()));
        }
        def(
            "memory store",
            &t.name,
            Some(&t.name),
            format!(
                "CREATE MEMORY STORE {} USING {}{}",
                ident(&t.name),
                ident(&spec.model),
                with(&options)
            ),
        );
    }
    for t in by_shape(Shape::Chunks) {
        let spec = t.chunks.as_ref().expect("a chunk table");
        let Some(fk) = t.foreign_keys.iter().find(|f| f.name == spec.fk) else {
            continue;
        };
        let column = tables
            .iter()
            .find(|s| s.name == fk.table)
            .and_then(|s| s.columns.get(spec.column))
            .map_or(String::new(), |c| ident(&c.name));
        let mut sql = format!(
            "CREATE TABLE {} CHUNKS OF {} ({column}) BY {} SIZE {}",
            ident(&t.name),
            ident(&fk.table),
            ident(&spec.by),
            spec.size
        );
        if spec.overlap != 0 {
            sql.push_str(&format!(" OVERLAP {}", spec.overlap));
        }
        if let Some(m) = &spec.model {
            sql.push_str(&format!(" USING {}", ident(m)));
        }
        def("chunk table", &t.name, Some(&t.name), sql);
    }
    for t in by_shape(Shape::Collection) {
        let mut options = Vec::new();
        if let Some(schema) = crate::collection::schema(t) {
            options.push(("schema".to_string(), schema));
        }
        if t.storage != crate::storage::ROW && t.storage != crate::column_store::ROW_COLUMN {
            options.push(("storage".to_string(), t.storage.clone()));
        }
        if t.engine != catalog::TableEngine::BTree {
            options.push(("engine".to_string(), t.engine.name().to_string()));
        }
        def(
            "collection",
            &t.name,
            Some(&t.name),
            format!("CREATE COLLECTION {}{}", ident(&t.name), with(&options)),
        );
    }
    for t in by_shape(Shape::Stream) {
        // Its columns after seq and time, its constraints but the key.
        let mut parts: Vec<String> = t.columns[2..]
            .iter()
            .map(|c| column_sql_with(c, &identities))
            .collect();
        for c in catalog::constraints(std::slice::from_ref(t)) {
            if matches!(
                c.kind,
                catalog::ConstraintKind::ForeignKey(_) | catalog::ConstraintKind::PrimaryKey
            ) {
                continue;
            }
            parts.push(format!("CONSTRAINT {} {}", ident(&c.name), c.definition));
        }
        let spec = t.stream.clone().unwrap_or_default();
        let mut options = Vec::new();
        if let Some(r) = spec.retention {
            options.push(("retention".to_string(), r.to_string()));
        }
        if let Some(n) = spec.max_entries {
            options.push(("max_entries".to_string(), n.to_string()));
        }
        if t.engine != catalog::TableEngine::BTree {
            options.push(("engine".to_string(), t.engine.name().to_string()));
        }
        def(
            "stream",
            &t.name,
            Some(&t.name),
            format!(
                "CREATE STREAM {} ({}){}",
                ident(&t.name),
                parts.join(", "),
                with(&options)
            ),
        );
    }
    // What a memory store, chunk table or collection has beyond what its
    // statement made: columns, unique constraints, checks.
    for t in tables
        .iter()
        .filter(|t| matches!(shape(t), Shape::Memory | Shape::Chunks | Shape::Collection))
    {
        for (c, col) in t.columns.iter().enumerate() {
            if !made_column(t, c) {
                def(
                    "column",
                    &col.name,
                    Some(&t.name),
                    format!(
                        "ALTER TABLE {} ADD COLUMN {}",
                        ident(&t.name),
                        column_sql_with(col, &identities)
                    ),
                );
            }
        }
        for c in catalog::constraints(std::slice::from_ref(t)) {
            // A collection's own checks are its statement's.
            let own = shape(t) == Shape::Collection
                && [
                    "doc_object",
                    "id_not_array",
                    crate::collection::SCHEMA_CHECK,
                ]
                .contains(&c.name.as_str());
            if !own
                && matches!(
                    c.kind,
                    catalog::ConstraintKind::Unique(_) | catalog::ConstraintKind::Check(_)
                )
            {
                def(
                    "constraint",
                    &c.name,
                    Some(&t.name),
                    format!(
                        "ALTER TABLE {} ADD CONSTRAINT {} {}",
                        ident(&t.name),
                        ident(&c.name),
                        c.definition
                    ),
                );
            }
        }
    }

    // Indexes (a partitioned table's reach its partitions), statistics.
    for t in tables.iter().filter(|t| shape(t) != Shape::Partition) {
        for (i, ix) in t.indexes.iter().enumerate() {
            let own = match shape(t) {
                Shape::Plain => t.is_unique_constraint(i),
                Shape::Memory => memory_index(t, ix),
                _ => false,
            };
            if !own && !t.is_unique_constraint(i) {
                def("index", &ix.name, Some(&t.name), index_sql(t, ix));
            }
        }
        for st in &t.statistics {
            def(
                "statistics",
                &st.name,
                Some(&t.name),
                format!(
                    "CREATE STATISTICS {} ON {} FROM {}",
                    ident(&st.name),
                    list(t, &st.columns),
                    ident(&t.name)
                ),
            );
        }
    }

    // Foreign keys, after every table (a partition has its parent's; a
    // chunk table's to its documents is its statement's).
    for t in tables.iter().filter(|t| shape(t) != Shape::Partition) {
        for fk in &t.foreign_keys {
            if t.chunks.as_ref().is_some_and(|s| s.fk == fk.name) {
                continue;
            }
            let Some(parent) = tables.iter().find(|p| p.name == fk.table) else {
                continue;
            };
            def(
                "foreign key",
                &fk.name,
                Some(&t.name),
                format!(
                    "ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({}){}{}",
                    ident(&t.name),
                    ident(&fk.name),
                    list(t, &fk.columns),
                    ident(&parent.name),
                    list(parent, &fk.ref_columns),
                    fk_action("UPDATE", fk.on_update),
                    fk_action("DELETE", fk.on_delete),
                ),
            );
        }
    }

    // The sequences columns own (an identity column's is its own).
    for s in &sequences {
        if let Some((t, c)) = &s.owned_by
            && !identities.contains_key(&s.name)
        {
            def(
                "owned by",
                &s.name,
                Some(t),
                format!(
                    "ALTER SEQUENCE {} OWNED BY {}.{}",
                    ident(&s.name),
                    ident(t),
                    ident(c)
                ),
            );
        }
    }

    // Property graphs, over the tables (every default spelled out).
    for g in crate::graphs::all(txn)? {
        def(
            "property graph",
            &g.name,
            None,
            crate::graphs::definition(&g),
        );
    }

    // Comments, then each table's settings.
    for t in &tables {
        if let Some(c) = &t.comment {
            def(
                "comment",
                &t.name,
                Some(&t.name),
                format!("COMMENT ON TABLE {} IS {}", ident(&t.name), literal(c)),
            );
        }
        if shape(t) == Shape::Partition {
            continue;
        }
        for col in &t.columns {
            if let Some(c) = &col.comment {
                def(
                    "comment",
                    &format!("{}.{}", t.name, col.name),
                    Some(&t.name),
                    format!(
                        "COMMENT ON COLUMN {}.{} IS {}",
                        ident(&t.name),
                        ident(&col.name),
                        literal(c)
                    ),
                );
            }
        }
    }
    for t in tables.iter().filter(|t| shape(t) != Shape::Partition) {
        let alter = |what: String| format!("ALTER TABLE {} {what}", ident(&t.name));
        if t.storage == crate::column_store::ROW_COLUMN {
            let cols = if t.columnar.is_empty() {
                String::new()
            } else {
                format!(" ({})", list(t, &t.columnar))
            };
            def(
                "storage",
                &t.name,
                Some(&t.name),
                alter(format!("SET STORAGE row, column{cols}")),
            );
        }
        if let Some((storage, after)) = &t.storage_policy {
            def(
                "storage",
                &t.name,
                Some(&t.name),
                alter(format!(
                    "SET STORAGE POLICY ({} AFTER interval {})",
                    storage.split(',').map(ident).collect::<Vec<_>>().join(", "),
                    literal(&after.to_string())
                )),
            );
        }
        let memory = shape(t) == Shape::Memory;
        let (expiry, subject) = if memory {
            (
                t.column("expires_at"),
                t.column("subject").into_iter().collect(),
            )
        } else {
            (None, Vec::new())
        };
        if t.expiry != expiry {
            def(
                "expiry",
                &t.name,
                Some(&t.name),
                alter(match t.expiry {
                    Some(c) => format!("SET EXPIRY ({})", ident(&t.columns[c].name)),
                    None => "DROP EXPIRY".into(),
                }),
            );
        }
        if t.subject != subject {
            def(
                "subject",
                &t.name,
                Some(&t.name),
                alter(if t.subject.is_empty() {
                    "DROP SUBJECT".into()
                } else {
                    format!("SET SUBJECT ({})", list(t, &t.subject))
                }),
            );
        }
        if t.row_security {
            def(
                "row security",
                &t.name,
                Some(&t.name),
                alter("ENABLE ROW LEVEL SECURITY".into()),
            );
        }
        if t.force_row_security {
            def(
                "row security",
                &t.name,
                Some(&t.name),
                alter("FORCE ROW LEVEL SECURITY".into()),
            );
        }
    }
    for p in crate::policies::all(txn)? {
        let mut sql = format!("CREATE POLICY {} ON {}", ident(&p.name), ident(&p.table));
        if !p.permissive {
            sql.push_str(" AS RESTRICTIVE");
        }
        if p.command != crate::policies::Command::All {
            sql.push_str(&format!(" FOR {}", p.command.word()));
        }
        if !(p.roles.len() == 1 && p.roles[0] == "public") {
            sql.push_str(&format!(
                " TO {}",
                p.roles
                    .iter()
                    .map(|r| ident(r))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        if let Some(u) = &p.using {
            sql.push_str(&format!(" USING ({u})"));
        }
        if let Some(c) = &p.check {
            sql.push_str(&format!(" WITH CHECK ({c})"));
        }
        def("policy", &p.name, Some(&p.table), sql);
    }
    Ok(out)
}

/// The definitions as one script: each statement and its `;`, a line
/// each — what `nucleus dump --schema` prints.
pub fn script(defs: &[Definition]) -> String {
    defs.iter().map(|d| format!("{};\n", d.sql)).collect()
}

