//! Chunk tables kept current with their documents (PLAN.md §M14.22 E7):
//! `CREATE TABLE c CHUNKS OF docs (body) BY … SIZE …`, chunked again in
//! the writer's transaction, unchanged chunks keeping their rows and
//! vectors, the lineage's cascades, and what is refused.

use std::path::Path;
use std::sync::Arc;

use nucleus_kv::{Database, Kv, Options, TxnOptions};
use nucleus_platform::sim::SimPlatform;
use nucleus_sql::ext::Registry;
use nucleus_sql::{Output, Session, Value};

fn db() -> Arc<dyn Kv> {
    Arc::new(
        Database::open_on(
            Arc::new(SimPlatform::new(7)),
            Path::new("/db"),
            Options::default(),
        )
        .unwrap(),
    )
}

fn texts(s: &mut Session, sql: &str) -> Vec<String> {
    match s.execute(sql).unwrap().pop().unwrap() {
        Output::Rows { rows, .. } => rows
            .into_iter()
            .map(|r| {
                r.iter()
                    .map(|v| match v {
                        Value::Text(t) => t.replace('\n', "|"),
                        other => other.render(),
                    })
                    .collect::<Vec<_>>()
                    .join(" ")
            })
            .collect(),
        other => panic!("{other:?}"),
    }
}

fn code(s: &mut Session, sql: &str) -> String {
    s.execute(sql).unwrap_err().code.to_string()
}

fn consistent(kv: &Arc<dyn Kv>) {
    let txn = kv.begin(TxnOptions::read_only()).unwrap();
    let problems = nucleus_sql::check::check(&*txn, &Registry::builtin()).unwrap();
    assert_eq!(problems, Vec::<String>::new());
}

#[test]
fn chunks_follow_their_documents() {
    let kv = db();
    // The rounds are this test's: jobs stay where it can count them.
    nucleus_sql::embedding::rounds_by_caller(kv.as_ref());
    let reg = Registry::builtin();
    let mut s = Session::new(kv.clone());
    s.execute("CREATE TABLE docs (id int PRIMARY KEY, title text, body text)")
        .unwrap();
    s.execute(
        "INSERT INTO docs VALUES (1, 'a', E'# Intro\\n\\nOne two three.\\n\\n# Use\\n\\nFour five six.'), \
         (2, 'b', 'Short.'), (3, 'c', NULL)",
    )
    .unwrap();
    s.execute("CREATE TABLE parts CHUNKS OF docs (body) BY markdown SIZE 3")
        .unwrap();
    assert_eq!(
        texts(
            &mut s,
            "SELECT id, position, chunk, start, length, array_to_string(headings, '/'), size \
             FROM parts ORDER BY id, position"
        ),
        vec![
            "1 1 # Intro 1 7 Intro 1",
            "1 2 One two three. 10 14 Intro 3",
            "1 3 # Use 26 5 Use 1",
            "1 4 Four five six. 33 14 Use 3",
            "2 1 Short. 1 6  1",
        ]
    );
    assert_eq!(
        texts(&mut s, "SELECT * FROM nc_catalog.chunk_tables"),
        vec!["parts docs body markdown 3 0 NULL"]
    );
    // Vectors for the chunks: an embedding column over them.
    s.execute("CREATE MODEL h USING hashing WITH (dimensions = 8)")
        .unwrap();
    s.execute("ALTER TABLE parts ADD COLUMN v vector GENERATED BY EMBEDDING (chunk) USING h")
        .unwrap();
    let jobs =
        |s: &mut Session| texts(s, "SELECT count(*) FROM nc_catalog.embedding_jobs")[0].clone();
    assert_eq!(jobs(&mut s), "5");
    while nucleus_sql::embedding::work(&kv, &reg).unwrap().worked() {}
    assert_eq!(jobs(&mut s), "0");

    // One paragraph edited: one chunk made again, the rest kept.
    s.execute("UPDATE docs SET body = E'# Intro\\n\\nOne two three.\\n\\n# Use\\n\\nFour five seven.' WHERE id = 1")
        .unwrap();
    assert_eq!(
        texts(
            &mut s,
            "SELECT position, chunk, v IS NULL FROM parts WHERE id = 1 ORDER BY position"
        ),
        vec![
            "1 # Intro f",
            "2 One two three. f",
            "3 # Use f",
            "4 Four five seven. t"
        ]
    );
    assert_eq!(jobs(&mut s), "1");
    while nucleus_sql::embedding::work(&kv, &reg).unwrap().worked() {}

    // A paragraph put first: the others move down, keeping their vectors.
    s.execute("UPDATE docs SET body = E'Preface here.\\n\\n' || body WHERE id = 1")
        .unwrap();
    assert_eq!(
        texts(
            &mut s,
            "SELECT position, chunk, start, v IS NULL FROM parts WHERE id = 1 ORDER BY position"
        ),
        vec![
            "1 Preface here. 1 t",
            "2 # Intro 16 f",
            "3 One two three. 25 f",
            "4 # Use 41 f",
            "5 Four five seven. 48 f"
        ]
    );
    assert_eq!(jobs(&mut s), "1");
    // Another column of the document: nothing to chunk.
    s.execute("UPDATE docs SET title = 'z'").unwrap();
    assert_eq!(jobs(&mut s), "1");

    // The lineage: a key changed moves the chunks, a document deleted
    // takes them, a NULL text has none.
    s.execute("UPDATE docs SET id = 20 WHERE id = 2").unwrap();
    assert_eq!(
        texts(&mut s, "SELECT id, chunk FROM parts WHERE id IN (2, 20)"),
        vec!["20 Short."]
    );
    s.execute("DELETE FROM docs WHERE id = 1").unwrap();
    assert_eq!(texts(&mut s, "SELECT count(*) FROM parts"), vec!["1"]);
    s.execute("UPDATE docs SET body = 'Now some. Text here.' WHERE id = 3")
        .unwrap();
    s.execute("UPDATE docs SET body = NULL WHERE id = 20")
        .unwrap();
    assert_eq!(
        texts(
            &mut s,
            "SELECT id, position, chunk FROM parts ORDER BY id, position"
        ),
        vec!["3 1 Now some.", "3 2 Text here."]
    );
    // COPY and INSERT … SELECT reach it as any write does.
    s.execute("INSERT INTO docs SELECT id + 100, title, body FROM docs WHERE body IS NOT NULL")
        .unwrap();
    assert_eq!(texts(&mut s, "SELECT count(*) FROM parts"), vec!["4"]);
    consistent(&kv);

    // Its rows are its documents': not written by hand …
    assert_eq!(
        code(
            &mut s,
            "INSERT INTO parts (id, position, chunk, start, length, headings, size) VALUES (3, 9, 'x', 1, 1, '{}', 1)"
        ),
        "42809"
    );
    assert_eq!(code(&mut s, "DELETE FROM parts"), "42809");
    assert_eq!(code(&mut s, "UPDATE parts SET chunk = 'x'"), "42809");
    assert_eq!(code(&mut s, "UPDATE parts SET id = 5"), "42809");
    // … but a column added to it is the user's.
    s.execute("ALTER TABLE parts ADD COLUMN note text").unwrap();
    s.execute("UPDATE parts SET note = 'seen'").unwrap();
    assert_eq!(
        code(
            &mut s,
            "ALTER TABLE parts DROP CONSTRAINT parts_document_fkey"
        ),
        "2BP01"
    );
    assert_eq!(
        code(
            &mut s,
            "ALTER TABLE docs ALTER COLUMN body TYPE varchar(100)"
        ),
        "0A000"
    );
    assert_eq!(
        code(
            &mut s,
            "ALTER TABLE parts ALTER COLUMN chunk TYPE varchar(100)"
        ),
        "0A000"
    );
    // What a chunk table is made of.
    assert_eq!(
        code(
            &mut s,
            "CREATE TABLE p2 CHUNKS OF docs (id) BY sentences SIZE 4"
        ),
        "42804"
    );
    assert_eq!(
        code(
            &mut s,
            "CREATE TABLE p2 CHUNKS OF docs (nope) BY sentences SIZE 4"
        ),
        "42703"
    );
    assert_eq!(
        code(
            &mut s,
            "CREATE TABLE p2 CHUNKS OF docs (body) BY lines SIZE 4"
        ),
        "22023"
    );
    assert_eq!(
        code(
            &mut s,
            "CREATE TABLE p2 CHUNKS OF docs (body) BY tokens SIZE 4 OVERLAP 4"
        ),
        "22023"
    );
    assert_eq!(
        code(
            &mut s,
            "CREATE TABLE p2 CHUNKS OF docs (body) BY tokens SIZE 4 USING h"
        ),
        "0A000"
    );
    s.execute("CREATE TABLE nokey (body text)").unwrap();
    assert_eq!(
        code(
            &mut s,
            "CREATE TABLE p2 CHUNKS OF nokey (body) BY tokens SIZE 4"
        ),
        "42P17"
    );
    // Two chunk tables of one table, cut differently.
    s.execute("CREATE TABLE words CHUNKS OF docs (body) BY tokens SIZE 2 OVERLAP 1")
        .unwrap();
    assert_eq!(
        texts(
            &mut s,
            "SELECT chunk FROM words WHERE id = 3 ORDER BY position"
        ),
        vec!["Now some.", "some. Text", "Text here."]
    );
    // Dropped with its documents only when asked.
    assert_eq!(code(&mut s, "DROP TABLE docs"), "2BP01");
    s.execute("DROP TABLE docs CASCADE").unwrap();
    assert_eq!(
        texts(
            &mut s,
            "SELECT count(*) FROM nc_catalog.tables WHERE name IN ('docs', 'parts', 'words')"
        ),
        vec!["0"]
    );
    assert_eq!(jobs(&mut s), "0");
    consistent(&kv);
}
