//! The schema as SQL (PLAN.md §M14.16 M1): `nc_catalog.definitions`.
//!
//! The law: a schema's definitions, run on an empty database, give the
//! same definitions — for a schema with every kind of object, and for the
//! schema each of the test kit's scripts leaves behind.

use std::path::Path;
use std::sync::Arc;

use nucleus_kv::{Database, Kv, Options};
use nucleus_platform::sim::SimPlatform;
use nucleus_sql::{Output, Session, Value};
use nucleus_testkit::slt::{Connection, Local, run_script};

fn db() -> Arc<dyn Kv> {
    Arc::new(
        Database::open_on(
            Arc::new(SimPlatform::new(1)),
            Path::new("/db"),
            Options::default(),
        )
        .unwrap(),
    )
}

fn run(s: &mut Session, sql: &str) {
    s.execute(sql).unwrap_or_else(|e| panic!("{sql}: {e:?}"));
}

/// (kind, name, table, definition) of every definition.
fn definitions(s: &mut Session) -> Vec<[String; 4]> {
    match s
        .execute("SELECT kind, name, table_name, definition FROM nc_catalog.definitions ORDER BY position")
        .unwrap()
        .pop()
        .unwrap()
    {
        Output::Rows { rows, .. } => rows
            .into_iter()
            .map(|r| {
                let t = |v: &Value| match v {
                    Value::Null => String::new(),
                    v => v.render(),
                };
                [t(&r[0]), t(&r[1]), t(&r[2]), t(&r[3])]
            })
            .collect(),
        other => panic!("{other:?}"),
    }
}

/// Runs `defs` on an empty database; its definitions then.  Each runs
/// alone, as `nucleus dump --schema`'s script would.
fn replayed(defs: &[[String; 4]]) -> Result<Vec<[String; 4]>, String> {
    let mut s = Session::new(db());
    for d in defs {
        s.execute(&d[3])
            .map_err(|e| format!("{}: {} ({})", d[3], e.message, e.code))?;
    }
    Ok(definitions(&mut s))
}

fn assert_replays(defs: &[[String; 4]]) {
    let again = replayed(defs).unwrap_or_else(|e| panic!("{e}"));
    for (a, b) in defs.iter().zip(&again) {
        assert_eq!(a, b, "a definition changed on replay");
    }
    assert_eq!(defs.len(), again.len(), "{defs:#?}\n\n{again:#?}");
}

