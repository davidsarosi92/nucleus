#[test]
fn a_schema_of_every_kind_replays() {
    let mut s = Session::new(db());
    for stmt in SCHEMA.split(";\n").filter(|x| !x.trim().is_empty()) {
        run(&mut s, stmt);
    }
    let defs = definitions(&mut s);
    if std::env::var_os("SHOW").is_some() {
        for d in &defs {
            println!("{};", d[3]);
        }
    }
    let kinds: Vec<&str> = defs.iter().map(|d| d[0].as_str()).collect();
    for k in [
        "model",
        "type",
        "ordering",
        "table",
        "partition",
        "memory store",
        "chunk table",
        "column",
        "index",
        "statistics",
        "foreign key",
        "comment",
        "storage",
        "expiry",
        "subject",
        "row security",
        "policy",
        "property graph",
    ] {
        assert!(kinds.contains(&k), "no {k} in {defs:#?}");
    }
    assert_replays(&defs);
    // A column of a quoted table, quoted where it must be.
    assert!(
        defs.iter().any(|d| d[3].starts_with(
            "CREATE TABLE \"Emp Loyees\" (id bigint NOT NULL, dept_id integer, \"select\" text,"
        )),
        "{defs:#?}"
    );
}

/// The schema each of the test kit's scripts leaves, replayed.
#[test]
fn the_scripts_schemas_replay() {
    let mut failures = Vec::new();
    for (name, script) in nucleus_testkit::core_scripts() {
        if !nucleus_testkit::picked(name) {
            continue;
        }
        let kv = db();
        let mut connect =
            || -> Box<dyn Connection> { Box::new(Local(Session::new(Arc::clone(&kv)))) };
        run_script(script, name, &mut connect);
        let defs = definitions(&mut Session::new(Arc::clone(&kv)));
        match replayed(&defs) {
            Ok(again) if again == defs => {}
            Ok(again) => {
                let diff: Vec<_> = defs
                    .iter()
                    .zip(&again)
                    .filter(|(a, b)| a != b)
                    .take(3)
                    .collect();
                failures.push(format!(
                    "{name}: {diff:#?} ({} / {})",
                    defs.len(),
                    again.len()
                ));
            }
            Err(e) => failures.push(format!("{name}: {e}")),
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n\n"));
}
