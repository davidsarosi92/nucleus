#!/usr/bin/env python3
"""The public data full-text search is built and checked against
(PLAN.md §M14.21), fetched once into target/text-data:

    bench/text/data.py [--out target/text-data] [what ...]

what (default: all of them):

    unicode     the Unicode 16 word-break property, its test, emoji data
                (scripts/gen-word-breaks.py; words.rs's test)
    snowball    Snowball's vocabularies at the commit of Snowball 3.0.1,
                the version the stemmers were generated by — every word of
                each language is then checked, not the fortieth in
                crates/sql/tests/data
    stop        Snowball's stop-word lists (scripts/gen-stop-words.py)
    beir        BEIR's SciFact, NFCorpus, ArguAna and FiQA (corpus,
                queries, relevance judgements), as BEIR publishes them
    msmarco     BEIR's MS MARCO passage (8.8 million passages, 1 GB
                zipped; not fetched by default): its test judgements are
                TREC DL 2019's (§M14.21 T5b)

Files go through curl (this machine's Python lacks certificates).
"""

import argparse
import os
import subprocess
import zipfile

UNICODE = "https://www.unicode.org/Public/16.0.0/ucd/"
SNOWBALL_DATA = (
    "https://raw.githubusercontent.com/snowballstem/snowball-data/"
    "381b447563f9bef87b218ebbedde3159afdc3032/"
)
STOP = "https://raw.githubusercontent.com/snowballstem/snowball-website/main/algorithms/"
BEIR = "https://public.ukp.informatik.tu-darmstadt.de/thakur/BEIR/datasets/"
LANGUAGES = [
    "danish", "dutch", "english", "finnish", "french", "german", "hungarian",
    "italian", "norwegian", "porter", "portuguese", "russian", "spanish",
    "swedish",
]
DATASETS = ["scifact", "nfcorpus", "arguana", "fiqa"]


def fetch(url, path):
    if os.path.exists(path):
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    subprocess.run(
        # Resumed where a cut-short fetch stopped (MS MARCO's 1 GB).
        ["curl", "-sS", "-f", "-L", "-C", "-", "--max-time", "3600", "-o", path + ".part", url],
        check=True,
    )
    os.replace(path + ".part", path)


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--out", default="target/text-data")
    p.add_argument("what", nargs="*", default=["unicode", "snowball", "stop", "beir"])
    a = p.parse_args()
    out = a.out
    if "unicode" in a.what:
        for f in ["auxiliary/WordBreakProperty.txt", "auxiliary/WordBreakTest.txt",
                  "emoji/emoji-data.txt"]:
            fetch(UNICODE + f, os.path.join(out, "unicode", os.path.basename(f)))
    if "snowball" in a.what:
        for lang in LANGUAGES:
            for f in ["voc.txt", "output.txt"]:
                fetch(SNOWBALL_DATA + f"{lang}/{f}",
                      os.path.join(out, "snowball-data", lang, f))
    if "stop" in a.what:
        for lang in LANGUAGES:
            if lang != "porter":
                fetch(STOP + f"{lang}/stop.txt", os.path.join(out, "snowball-stop", lang + ".txt"))
    sets = (DATASETS if "beir" in a.what else []) + (["msmarco"] if "msmarco" in a.what else [])
    for d in sets:
        z = os.path.join(out, "zips", d + ".zip")
        fetch(BEIR + d + ".zip", z)
        dest = os.path.join(out, "beir-" + d)
        if not os.path.exists(os.path.join(dest, d, "corpus.jsonl")):
            with zipfile.ZipFile(z) as f:
                f.extractall(dest)


if __name__ == "__main__":
    main()
