#!/usr/bin/env python3
"""§M14.22's *Done when*, checked whole on BEIR (PLAN.md §M14.22 E8b):
documents to ranked chunks, by a local model, in the database.

    bench/embed/beir.py BINARY [--sets scifact,nfcorpus,arguana] [--models target/models]
                               [--model bge-small-en-v1.5] [--data target/text-data]
                               [--chunks 'sentences 200']

For each set, in a new server (`BINARY server DIR --no-auth`):

1. `CREATE MODEL bge USING local WITH (path = …)` — the files from
   disk, kept in the database; no call leaves the machine.
2. `docs (id, body, v vector GENERATED BY EMBEDDING (body) USING bge)`,
   a chunk table `parts CHUNKS OF docs (body) BY … USING bge` with its
   own embedding column, and an HNSW index on each — made empty, so
   loading the corpus is what fills them.
3. The corpus loaded; the server killed (`SIGKILL`) when about half the
   jobs are done and started again; its queue finishes.
4. Ranked: each judged query as `ORDER BY v <=> embed(q, 'bge',
   'query') LIMIT …` — documents directly, and chunks with each
   document scored by its best chunk — scored by nDCG@10 as
   `bench/text/beir.py` scores them; beside them, the documents'
   vectors searched exactly (here, in numpy) and fastembed's vectors of
   the same model (`bench/text/embed.py`) searched exactly.
5. Kept in sync: a tenth of the documents rewritten, a twentieth
   deleted; then all put back as they were, the server killed again
   once the queue's first round has committed.  Once it is empty, every chunk and vector
   must be the same as before, bit for bit (the encoder gives the same
   bits on any threads and in any batch), and no document without its
   chunks.

Run it under a memory cap (`target/bench-tools/memcap.sh`).
"""

import argparse
import json
import os
import shutil
import signal
import subprocess
import sys
import tempfile
import time

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "text"))
import beir  # noqa: E402

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                                "drivers", "python"))
import nucleus  # noqa: E402

lit = beir.lit


class Server:
    """A nucleus server on `dir`, started and killed at will."""

    def __init__(self, binary, dir, port):
        self.binary, self.dir, self.port = binary, dir, port
        self.p = None

    def start(self):
        self.p = subprocess.Popen([self.binary, "server", self.dir, "--listen",
                                   f"127.0.0.1:{self.port}", "--no-auth"],
                                  stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        for _ in range(1200):
            try:
                return nucleus.connect("127.0.0.1", self.port, password=None)
            except (OSError, nucleus.OperationalError):
                time.sleep(0.05)
        raise RuntimeError("the server did not start")

    def kill(self):
        self.p.send_signal(signal.SIGKILL)
        self.p.wait()

    def stop(self):
        if self.p and self.p.poll() is None:
            self.p.terminate()
            self.p.wait()


def jobs(c):
    """The queue: (jobs, of them failed)."""
    rows = c.execute("SELECT state, count(*) FROM nc_catalog.embedding_jobs GROUP BY state").rows
    n = sum(r[1] for r in rows)
    failed = sum(r[1] for r in rows if r[0] == "failed")
    return n, failed


def tokens(c):
    return c.execute("SELECT tokens FROM nc_catalog.models WHERE name = 'bge'").rows[0][0]


def drain(server, c, crash_at=None):
    """Waits for the queue to empty, killing the server once when no
    more than `crash_at` of its jobs are left; the connection, the
    seconds it took, the tokens embedded and whether it crashed."""
    t = time.time()
    spent, crashed = 0, False
    while True:
        n, failed = jobs(c)
        if failed:
            raise RuntimeError(f"{failed} jobs failed")
        if n == 0:
            return c, time.time() - t, spent + tokens(c), crashed
        if crash_at is not None and not crashed and n <= crash_at:
            spent += tokens(c)
            server.kill()
            c = server.start()
            crashed = True
            print(f"    killed with {n} jobs left; started again", file=sys.stderr, flush=True)
        time.sleep(0.5)


def ranked_docs(c, q, k=11):
    rows = c.execute(f"SELECT id FROM docs ORDER BY v <=> embed({lit(q)}, 'bge', 'query') "
                     f"LIMIT {k}").rows
    return [r[0] for r in rows]


def ranked_chunks(c, q, k=100):
    """Documents by their best chunk (the first `k` chunks)."""
    rows = c.execute(f"SELECT id FROM parts ORDER BY v <=> embed({lit(q)}, 'bge', 'query') "
                     f"LIMIT {k}").rows
    out = []
    for (i,) in rows:
        if i not in out:
            out.append(i)
    return out


def ndcg(rankings, qrels):
    s = [beir.ndcg10([d for d in rankings[q] if d != q][:10], rels) for q, rels in qrels.items()]
    return sum(s) / len(s)


def exact(doc_ids, docs, queries, qids):
    """Each query's documents by cosine, all of them compared."""
    d = docs / np.linalg.norm(docs, axis=1, keepdims=True)
    out = {}
    for qid, q in zip(qids, queries):
        s = d @ (q / np.linalg.norm(q))
        out[qid] = [doc_ids[i] for i in np.argsort(-s, kind="stable")[:11]]
    return out


def vectors(c, sql):
    rows = c.execute(sql).rows
    return [r[0] for r in rows], np.array([json.loads(r[1]) for r in rows], dtype=np.float32)


def snapshot(c):
    return c.execute("SELECT id, position, chunk, start, length, size, v::text FROM parts "
                     "ORDER BY id, position").rows


def run(a, name):
    d = os.path.join(a.data, f"beir-{name}", name)
    docs = list(beir.corpus(d))
    queries, qrels = beir.load(d)
    by, size = a.chunks.split()
    work = tempfile.mkdtemp(prefix="nucleus-embed-beir-")
    server = Server(a.binary, os.path.join(work, "db"), a.port)
    try:
        c = server.start()
        c.execute(f"CREATE MODEL bge USING local WITH (path = "
                  f"{lit(os.path.abspath(os.path.join(a.models, a.model)))})")
        c.execute("CREATE TABLE docs (id text PRIMARY KEY, body text, "
                  "v vector(384) GENERATED BY EMBEDDING (body) USING bge)")
        c.execute(f"CREATE TABLE parts CHUNKS OF docs (body) BY {by} SIZE {size} USING bge")
        c.execute("ALTER TABLE parts ADD COLUMN v vector(384) "
                  "GENERATED BY EMBEDDING (chunk) USING bge")
        c.execute("CREATE INDEX docs_v ON docs USING hnsw (v vector_cosine_ops)")
        c.execute("CREATE INDEX parts_v ON parts USING hnsw (v vector_cosine_ops)")

        t = time.time()
        for i in range(0, len(docs), 500):
            part = docs[i:i + 500]
            c.load("docs", {"id": [x for x, _ in part], "body": [b for _, b in part]})
        load_s = time.time() - t
        nchunks = c.execute("SELECT count(*) FROM parts").rows[0][0]
        njobs, _ = jobs(c)
        c, embed_s, ntokens, crashed = drain(server, c, crash_at=njobs // 2)
        assert crashed
        print(f"  {name}: {len(docs)} documents, {nchunks} chunks ({by} of {size} tokens): "
              f"loaded and chunked in {load_s:.1f} s; {njobs} vectors in {embed_s:.0f} s "
              f"({njobs / embed_s:.0f} a second, {ntokens / embed_s:.0f} tokens a second), "
              f"the server killed once", flush=True)

        def rank_all():
            rd = {q: ranked_docs(c, queries[q]) for q in qrels}
            rc = {q: ranked_chunks(c, queries[q]) for q in qrels}
            return rd, rc

        rd, rc = rank_all()
        ids, dv = vectors(c, "SELECT id, v::text FROM docs ORDER BY id")
        qids = list(qrels)
        _, qv = vectors(c, "SELECT q, embed(q, 'bge', 'query')::text FROM (VALUES "
                        + ", ".join(f"({lit(queries[q])})" for q in qids) + ") t(q)")
        ours_exact = ndcg(exact(ids, dv, qv, qids), qrels)
        theirs = None
        if os.path.exists(os.path.join(d, "dense-docs.npy")):
            fe = json.load(open(os.path.join(d, "ids.json")))
            assert fe["queries"] == qids
            theirs = ndcg(exact(fe["docs"], np.load(os.path.join(d, "dense-docs.npy")),
                                np.load(os.path.join(d, "dense-queries.npy")), qids), qrels)
        before = snapshot(c)

        # Rewritten and deleted, then put back as they were.
        rewritten = docs[3::10]
        deleted = docs[7::20]
        for i, b in rewritten:
            c.execute(f"UPDATE docs SET body = upper(body) || ' (revised)' WHERE id = {lit(i)}")
        c.execute("DELETE FROM docs WHERE id IN (" + ", ".join(lit(i) for i, _ in deleted) + ")")
        c, _, _, _ = drain(server, c)
        changed = c.execute("SELECT count(*) FROM parts WHERE chunk LIKE '%(revised)'").rows[0][0]
        assert changed == len([1 for _, b in rewritten if b.strip()]), changed
        for i, b in rewritten:
            c.execute(f"UPDATE docs SET body = {lit(b)} WHERE id = {lit(i)}")
        c.load("docs", {"id": [i for i, _ in deleted], "body": [b for _, b in deleted]})
        left, _ = jobs(c)
        # Killed once the first round has committed: the texts that were
        # embedded before are the cache's, so the queue may empty fast.
        c, sync_s, _, crashed = drain(server, c, crash_at=left - 1)
        after = snapshot(c)
        same = after == before
        orphans = c.execute("SELECT count(*) FROM docs d WHERE length(trim(body)) > 0 AND NOT "
                            "EXISTS (SELECT 1 FROM parts p WHERE p.id = d.id)").rows[0][0]
        rd2, rc2 = rank_all()
        print(f"  {name}: {len(rewritten)} rewritten and {len(deleted)} deleted, then put back "
              f"({left} jobs, {sync_s:.0f} s, the server killed {'once' if crashed else 'never'}): "
              f"chunks and vectors {'the same, bit for bit' if same else 'DIFFERENT'}; "
              f"documents without chunks: {orphans}", flush=True)
        assert same and orphans == 0
        return {
            "set": name, "docs": len(docs), "chunks": nchunks, "queries": len(qrels),
            "docs_hnsw": ndcg(rd, qrels), "chunks_hnsw": ndcg(rc, qrels),
            "docs_exact": ours_exact, "fastembed_exact": theirs,
            "docs_hnsw_after": ndcg(rd2, qrels), "chunks_hnsw_after": ndcg(rc2, qrels),
            "vectors_per_s": njobs / embed_s,
        }
    finally:
        server.stop()
        shutil.rmtree(work)


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("binary")
    p.add_argument("--sets", default="scifact,nfcorpus,arguana")
    p.add_argument("--data", default="target/text-data")
    p.add_argument("--models", default="target/models")
    p.add_argument("--model", default="bge-small-en-v1.5")
    p.add_argument("--chunks", default="sentences 200")
    p.add_argument("--port", type=int, default=21019)
    a = p.parse_args()
    results = [run(a, s) for s in a.sets.split(",")]
    print()
    print(f"{'nDCG@10':10} {'docs':>8} {'chunks':>8} {'docs, exact':>12} {'fastembed':>10} "
          f"{'docs after':>11} {'chunks after':>13}")
    for r in results:
        fe = f"{r['fastembed_exact']:10.4f}" if r["fastembed_exact"] is not None else f"{'-':>10}"
        print(f"{r['set']:10} {r['docs_hnsw']:8.4f} {r['chunks_hnsw']:8.4f} "
              f"{r['docs_exact']:12.4f} {fe} {r['docs_hnsw_after']:11.4f} "
              f"{r['chunks_hnsw_after']:13.4f}")


if __name__ == "__main__":
    main()
